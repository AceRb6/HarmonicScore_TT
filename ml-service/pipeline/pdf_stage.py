def _find_group_end(svg: str, start_idx: int) -> int:
    """
    Dado el índice de '<g', devuelve el índice JUSTO DESPUÉS de su '</g>' de
    cierre, contando anidamiento y respetando self-closing '<g ... />'. -1 si falla.
    """
    depth = 0
    i = start_idx
    n = len(svg)
    while i < n:
        next_g = svg.find('<g', i)
        next_close = svg.find('</g>', i)
        if next_close == -1:
            return -1
        if next_g != -1 and next_g < next_close:
            gt = svg.find('>', next_g)
            if gt == -1:
                return -1
            if svg[gt - 1:gt] != '/':   # '<g ... />' no abre bloque; '<g ...>' sí
                depth += 1
            i = gt + 1
        else:
            depth -= 1
            i = next_close + 4
            if depth == 0:
                return i
    return -1


def _inject_chrome(svg: str, title: str, page_num: int, total_pages: int) -> str:
    """
    Header: NO se inyecta a mano. Con header:'first' Verovio pinta el título
    nativo (desde md.title) SOLO en pág.1, con su propia franja reservada.
    En pág.2+ Verovio deja un residuo ('at~ 2 at~'); lo VACIAMOS con _find_group_end.
    Footer: se inyecta a mano en coords absolutas (validado: no pisa música).
    Sin 're'.
    """
    page_label = f"Página {page_num} de {total_pages}" if total_pages > 1 else ""

    # --- 1) pág.2+: vaciar el pgHead nativo (mata 'at~ 2 at~') ---
    if page_num > 1:
        hi = svg.find('class="pgHead autogenerated"')
        if hi != -1:
            hs = svg.rfind('<g ', 0, hi)
            he = _find_group_end(svg, hs) if hs != -1 else -1
            if hs != -1 and he != -1:
                svg = svg[:hs] + '<g class="pgHead"/>' + svg[he:]

    # --- 2) footer manual en coords absolutas (idéntico al que ya funcionó) ---
    CX = 10500
    Y_MID, Y_BOT = 28200, 28700
    footer_block = (
        '<g id="hs_foot">'
        f'<text x="{CX}" y="{Y_MID}" text-anchor="middle" '
        f'font-family="sans-serif" font-size="330" fill="#666666">{WATERMARK}</text>'
        f'<text x="{CX}" y="{Y_BOT}" text-anchor="middle" '
        f'font-family="sans-serif" font-size="300" fill="#888888">{page_label}</text>'
        '</g>'
    )
    close_root = svg.rfind('</svg>')
    close_def = svg.rfind('</svg>', 0, close_root) if close_root != -1 else -1
    if close_def == -1:
        return svg
    return svg[:close_def] + footer_block + svg[close_def:]


def musicxml_a_svg(xml_path: Path, title: str = "") -> list[str]:
    """
    Verovio 4.3.1 -> SVG. header:'first' => título nativo con aire solo en pág.1
    (el residuo de pág.2+ se limpia en _inject_chrome). footer:'none' porque el
    pie lo inyectamos a mano en coords absolutas (franja inferior reservada por
    pageMarginBottom). Al no tocar el final del SVG, se preserva el <style>
    'Leipzig' => la negra ♩ del metrónomo se conserva.
    """
    import verovio
    tk = verovio.toolkit()
    tk.setOptions({
        "header": "auto",     
        "footer": "none",      
        "pageMarginTop": 25,
        "pageMarginBottom": 30,  
        "pageMarginLeft": 15,
        "pageMarginRight": 15,
    })
    if not tk.loadFile(str(xml_path)):
        raise RuntimeError(f"Verovio no pudo cargar el MusicXML: {xml_path}")
    n_pages = tk.getPageCount()
    if not n_pages:
        raise RuntimeError("Verovio no generó páginas (MusicXML vacío o inválido)")
    return [_inject_chrome(tk.renderToSVG(i), title, i, n_pages) for i in range(1, n_pages + 1)]

def _merge_pdfs(tmp_pdfs: list[Path], pdf_path: Path) -> None:
    from pypdf import PdfWriter
    writer = PdfWriter()
    for p in tmp_pdfs:
        writer.append(str(p))
    with open(pdf_path, "wb") as fh:
        writer.write(fh)


def _pdf_via_cairosvg(svgs: list[str], pdf_path: Path, workdir: Path) -> None:
    import cairosvg
    tmp = []
    for i, svg in enumerate(svgs, 1):
        p = workdir / f"page_{i:03d}.pdf"
        cairosvg.svg2pdf(bytestring=svg.encode("utf-8"), write_to=str(p))
        tmp.append(p)
    _merge_pdfs(tmp, pdf_path)


def _pdf_via_edge(svgs: list[str], pdf_path: Path, workdir: Path) -> None:
    edge = next((Path(c) for c in EDGE_CANDIDATES if Path(c).exists()), None)
    if edge is None:
        raise RuntimeError("No se encontró msedge.exe")

    html = workdir / "score.html"
    pages = "\n".join(f'<section class="page">{s}</section>' for s in svgs)
    html.write_text(
        "<!DOCTYPE html><html><head><meta charset='utf-8'><style>"
        "@page{size:A4 portrait;margin:12mm}"
        "html,body{margin:0;padding:0}"
        ".page{page-break-after:always;display:flex;align-items:center;justify-content:center}"
        ".page:last-child{page-break-after:auto}"
        ".page svg{max-width:100%;height:auto}"
        "</style></head><body>" + pages + "</body></html>",
        encoding="utf-8",
    )
    cmd = [
        str(edge), "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
        f"--print-to-pdf={pdf_path}",
        f"--user-data-dir={workdir / 'edge-profile'}",
        "--no-first-run", "--no-default-browser-check",
        "--disable-extensions", "--disable-popup-blocking",
        "--hide-scrollbars", "--virtual-time-budget=10000",
        html.as_uri(),
    ]
    r = subprocess.run(cmd, capture_output=True, timeout=180)
    if not pdf_path.exists():
        raise RuntimeError(f"Edge no generó el PDF: {r.stderr.decode(errors='ignore')[:400]}")


def _pdf_via_svglib(svgs: list[str], pdf_path: Path, workdir: Path) -> None:
    from svglib.svglib import svg2rlg
    from reportlab.graphics import renderPDF
    tmp = []
    for i, svg in enumerate(svgs, 1):
        drawing = svg2rlg(io.StringIO(svg))
        if drawing is None:
            raise RuntimeError("svglib no pudo interpretar el SVG")
        p = workdir / f"page_{i:03d}.pdf"
        renderPDF.drawToFile(drawing, str(p))
        tmp.append(p)
    _merge_pdfs(tmp, pdf_path)


def render_musicxml_to_pdf(xml_path: Path, pdf_path: Path, title: str = "") -> Path:
    """Convierte un MusicXML a PDF usando la primera estrategia que funcione."""
    xml_path, pdf_path = Path(xml_path), Path(pdf_path)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)

    svgs = musicxml_a_svg(xml_path, title=title)
    errores = []
    with tempfile.TemporaryDirectory(prefix="hs_pdf_") as td:
        workdir = Path(td)
        for nombre, fn in (("cairosvg", _pdf_via_cairosvg),
                           ("edge-headless", _pdf_via_edge),
                           ("svglib", _pdf_via_svglib)):
            try:
                fn(svgs, pdf_path, workdir)
                log.info("PDF generado vía %s: %s (%d página(s))", nombre, pdf_path, len(svgs))
                return pdf_path
            except Exception as e:
                errores.append(f"{nombre}: {e}")
                log.warning("Ruta de render %s falló: %s", nombre, e)
    raise RuntimeError("No se pudo generar el PDF: " + " | ".join(errores))