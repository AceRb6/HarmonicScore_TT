"""
Etapa 6b — Renderizado MusicXML 4.0 → PDF (RF-13).

Cadena de estrategias (deltas D1/D3 del TT-II):
  1) cairosvg        → Linux/CI (libcairo).
  2) Edge headless   → Windows de desarrollo (D3).
  3) svglib+reportlab→ último recurso.

Nota arquitectónica:
  - El título de la pieza se toma de los metadatos del MusicXML (md.title),
    no se inyecta manualmente. Verovio lo renderiza nativamente en pág.1.
  - El footer con watermark se inyecta manualmente en coordenadas absolutas
    del SVG de Verovio (21000 x 29700 twips para A4).
"""
from __future__ import annotations

import io
import logging
import subprocess
import tempfile
from pathlib import Path

log = logging.getLogger("harmonic.pdf_stage")

# =====================================================================
# Constantes de renderizado
# =====================================================================

# Rutas candidatas de Microsoft Edge en Windows (para fallback headless)
EDGE_CANDIDATES = (
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
)

# Watermark que aparece en el pie de cada página
WATERMARK = "Transcrito por Harmonic Score"

# Coordenadas absolutas del SVG de Verovio (twips, 1/20 de punto)
# El SVG de Verovio para A4 tiene dimensiones ~21000 x 29700 twips
SVG_CENTER_X = 10500
FOOTER_Y_MID = 28200  # Línea del watermark
FOOTER_Y_BOT = 28700  # Línea del número de página


# =====================================================================
# Utilidades de parseo de SVG
# =====================================================================

def _find_group_end(svg: str, start_idx: int) -> int:
    """
    Dado el índice de '<g', devuelve el índice JUSTO DESPUÉS de su '</g>' de
    cierre, contando anidamiento y respetando self-closing '<g ... />'.
    Retorna -1 si falla.
    """
    depth = 0
    i = start_idx
    n = len(svg)
    while i < n:
        next_g = svg.find('<g', i)
        next_close = svg.find('</g>', i)
        if next_close == -1:
            return -1
        if next_g != -1 and next_g < next_close:
            gt = svg.find('>', next_g)
            if gt == -1:
                return -1
            if svg[gt - 1:gt] != '/':   # '<g ... />' no abre bloque; '<g ...>' sí
                depth += 1
            i = gt + 1
        else:
            depth -= 1
            i = next_close + 4
            if depth == 0:
                return i
    return -1


def _is_valid_svg(svg: str) -> bool:
    """Validación básica de que el string es un SVG válido."""
    return '<svg' in svg and '</svg>' in svg


# =====================================================================
# Inyección de elementos visuales (chrome)
# =====================================================================

def _inject_chrome(svg: str, page_num: int, total_pages: int) -> str:
    """
    Inyecta elementos visuales (header/footer) en el SVG de Verovio.
    
    Nota: El título de la pieza NO se inyecta manualmente. Verovio lo renderiza
    nativamente desde los metadatos del MusicXML (md.title) SOLO en la página 1.
    En páginas 2+, Verovio deja un residuo ('at~ 2 at~') que vaciamos aquí.
    
    El footer se inyecta en coordenadas absolutas (franja inferior reservada
    por pageMarginBottom), garantizando que no pisa la notación musical.
    """
    if not _is_valid_svg(svg):
        log.warning(f"SVG inválido en página {page_num}, saltando inyección de chrome")
        return svg
    
    page_label = f"Página {page_num} de {total_pages}" if total_pages > 1 else ""

    # --- 1) pág.2+: vaciar el pgHead nativo (mata el residuo 'at~ 2 at~') ---
    if page_num > 1:
        hi = svg.find('class="pgHead autogenerated"')
        if hi != -1:
            hs = svg.rfind('<g ', 0, hi)
            he = _find_group_end(svg, hs) if hs != -1 else -1
            if hs != -1 and he != -1:
                svg = svg[:hs] + '<g class="pgHead"/>' + svg[he:]

    # --- 2) footer manual en coords absolutas ---
    footer_block = (
        '<g id="hs_foot">'
        f'<text x="{SVG_CENTER_X}" y="{FOOTER_Y_MID}" text-anchor="middle" '
        f'font-family="sans-serif" font-size="330" fill="#666666">{WATERMARK}</text>'
        f'<text x="{SVG_CENTER_X}" y="{FOOTER_Y_BOT}" text-anchor="middle" '
        f'font-family="sans-serif" font-size="300" fill="#888888">{page_label}</text>'
        '</g>'
    )
    
    # Insertar el footer justo antes del cierre del SVG raíz
    close_root = svg.rfind('</svg>')
    if close_root == -1:
        return svg
    
    return svg[:close_root] + footer_block + svg[close_root:]


# =====================================================================
# Conversión MusicXML → SVG (Verovio)
# =====================================================================

def musicxml_a_svg(xml_path: Path) -> list[str]:
    """
    Convierte MusicXML a lista de SVGs (uno por página) usando Verovio.
    
    Configuración:
    - header:'auto' => Verovio renderiza el título nativo en pág.1
    - footer:'none' => nosotros inyectamos el footer manualmente
    - pageMarginBottom:30 => reserva franja inferior para nuestro footer
    - No se toca el final del SVG para preservar el <style> 'Leipzig'
      (la negra ♩ del metrónomo se conserva)
    """
    import verovio
    
    tk = verovio.toolkit()
    tk.setOptions({
        "header": "auto",     
        "footer": "none",      
        "pageMarginTop": 25,
        "pageMarginBottom": 30,  
        "pageMarginLeft": 15,
        "pageMarginRight": 15,
    })
    
    if not tk.loadFile(str(xml_path)):
        raise RuntimeError(f"Verovio no pudo cargar el MusicXML: {xml_path}")
    
    n_pages = tk.getPageCount()
    if not n_pages:
        raise RuntimeError("Verovio no generó páginas (MusicXML vacío o inválido)")
    
    svgs = []
    for i in range(1, n_pages + 1):
        svg_raw = tk.renderToSVG(i)
        svg_clean = _inject_chrome(svg_raw, i, n_pages)
        svgs.append(svg_clean)
    
    return svgs


# =====================================================================
# Estrategias de renderizado SVG → PDF
# =====================================================================

def _merge_pdfs(tmp_pdfs: list[Path], pdf_path: Path) -> None:
    """Fusiona múltiples PDFs de página en uno solo usando pypdf."""
    from pypdf import PdfWriter
    writer = PdfWriter()
    for p in tmp_pdfs:
        writer.append(str(p))
    with open(pdf_path, "wb") as fh:
        writer.write(fh)


def _pdf_via_cairosvg(svgs: list[str], pdf_path: Path, workdir: Path) -> None:
    """Estrategia 1: CairoSVG (óptimo para Linux/CI con libcairo)."""
    import cairosvg
    tmp = []
    for i, svg in enumerate(svgs, 1):
        p = workdir / f"page_{i:03d}.pdf"
        cairosvg.svg2pdf(bytestring=svg.encode("utf-8"), write_to=str(p))
        tmp.append(p)
    _merge_pdfs(tmp, pdf_path)


def _pdf_via_edge(svgs: list[str], pdf_path: Path, workdir: Path) -> None:
    """
    Estrategia 2: Microsoft Edge headless (D3, óptimo para Windows).
    Genera un HTML wrapper con los SVGs y usa Edge para imprimir a PDF.
    """
    edge = next((Path(c) for c in EDGE_CANDIDATES if Path(c).exists()), None)
    if edge is None:
        raise RuntimeError("No se encontró msedge.exe en las rutas candidatas")

    html = workdir / "score.html"
    pages = "\n".join(f'<section class="page">{s}</section>' for s in svgs)
    html.write_text(
        "<!DOCTYPE html><html><head><meta charset='utf-8'><style>"
        "@page{size:A4 portrait;margin:12mm}"
        "html,body{margin:0;padding:0}"
        ".page{page-break-after:always;display:flex;align-items:center;justify-content:center}"
        ".page:last-child{page-break-after:auto}"
        ".page svg{max-width:100%;height:auto}"
        "</style></head><body>" + pages + "</body></html>",
        encoding="utf-8",
    )
    
    cmd = [
        str(edge), "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
        f"--print-to-pdf={pdf_path}",
        f"--user-data-dir={workdir / 'edge-profile'}",
        "--no-first-run", "--no-default-browser-check",
        "--disable-extensions", "--disable-popup-blocking",
        "--hide-scrollbars", "--virtual-time-budget=10000",
        html.as_uri(),
    ]
    
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=180)
    except subprocess.TimeoutExpired:
        raise RuntimeError("Edge headless excedió el timeout de 180s")
    except Exception as e:
        raise RuntimeError(f"Error ejecutando Edge: {e}") from e
    
    if r.returncode != 0:
        stderr = r.stderr.decode(errors='ignore')[:400] if r.stderr else "sin stderr"
        raise RuntimeError(f"Edge retornó código {r.returncode}: {stderr}")
    
    if not pdf_path.exists():
        raise RuntimeError(f"Edge no generó el PDF: {r.stderr.decode(errors='ignore')[:400]}")


def _pdf_via_svglib(svgs: list[str], pdf_path: Path, workdir: Path) -> None:
    """Estrategia 3: svglib + reportlab (último recurso, calidad reducida)."""
    from svglib.svglib import svg2rlg
    from reportlab.graphics import renderPDF
    tmp = []
    for i, svg in enumerate(svgs, 1):
        drawing = svg2rlg(io.StringIO(svg))
        if drawing is None:
            raise RuntimeError(f"svglib no pudo interpretar el SVG de la página {i}")
        p = workdir / f"page_{i:03d}.pdf"
        renderPDF.drawToFile(drawing, str(p))
        tmp.append(p)
    _merge_pdfs(tmp, pdf_path)


# =====================================================================
# API pública
# =====================================================================

def render_musicxml_to_pdf(xml_path: Path, pdf_path: Path, title: str = "") -> Path:
    """
    Convierte un MusicXML a PDF usando la primera estrategia que funcione.
    
    Args:
        xml_path: Ruta al archivo MusicXML de entrada
        pdf_path: Ruta de salida del PDF
        title: Título de la pieza (no se usa directamente; Verovio lo toma
               de los metadatos del MusicXML. Se mantiene por compatibilidad)
    
    Returns:
        Ruta del PDF generado
        
    Raises:
        RuntimeError: Si todas las estrategias de renderizado fallan
    """
    xml_path, pdf_path = Path(xml_path), Path(pdf_path)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)

    svgs = musicxml_a_svg(xml_path)
    
    errores = []
    with tempfile.TemporaryDirectory(prefix="hs_pdf_") as td:
        workdir = Path(td)
        for nombre, fn in (("cairosvg", _pdf_via_cairosvg),
                           ("edge-headless", _pdf_via_edge),
                           ("svglib", _pdf_via_svglib)):
            try:
                fn(svgs, pdf_path, workdir)
                log.info("PDF generado vía %s: %s (%d página(s))", 
                         nombre, pdf_path.name, len(svgs))
                return pdf_path
            except Exception as e:
                errores.append(f"{nombre}: {e}")
                log.warning("Ruta de render %s falló: %s", nombre, e)
    
    raise RuntimeError("No se pudo generar el PDF: " + " | ".join(errores))